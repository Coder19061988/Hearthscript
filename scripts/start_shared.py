# Спільний код: виконується в кожного персонажа першим.
# Тут пишуть функції, ролі та правила для всіх і розпорядок дня main().
# Код персонажа (вкладка «Код персонажа») виконується після спільного й має пріоритет:
# може перевизначити будь-що звідси, а off(правило) відміняє правило для цього персонажа.
# Після коду персонажа гра викликає main().
#
# Зараз поселенці лише їдять і сплять. Хліба на складі вистачить ненадовго,
# а через 10 днів зима — навчіть їх працювати (F1 — довідка).

storage = get("Склад_1")


def eat_until(limit):
    """Їсти хліб зі складу, поки голод вищий за limit."""
    while me.hunger > limit:
        try:
            me.pick_up(storage, "bread", 1)
        except NoItemError:
            notify("Хліб закінчився!")
            return
        me.eat("bread")


# Правило для всіх: уночі — спати, хоч би що персонаж робив у своєму коді.
# Код персонажа сильніший: його власне правило (наприклад, @on(time(21, 0)) — зміна до 23:00)
# це правило не перериває, свій def night_sleep замінює його, а off(night_sleep) — відміняє.
@on(lambda: world.time >= time(22, 0) or world.time < time(6, 0))
def night_sleep(me):
    eat_until(10)
    me.sleep(until=time(6, 0))


def work():
    """Денна робота. Перевизначте її в коді персонажа: def work(): ..."""
    me.rest(hours=1)


def main():
    """Розпорядок дня: поїсти й попрацювати (ніч — за правилом night_sleep)."""
    while True:
        eat_until(40)
        work()
